"""Book-independent linking of repository code to book chunks.

Linking cascade (first match wins per asset type):
1. Notebook cell tags  -- patterns like "Notebook Cell 3.1" / "# Cell 3.1"
   found in a chunk's text are resolved against cell tags discovered inside
   the repo's notebooks. A "current notebook" is inferred per chunk by
   fuzzy-matching the chunk's section header against notebook filenames
   (works for any chapter naming convention), and falls back to searching
   all notebooks.
2. %%writefile exports -- scripts generated by notebooks in the repo are
   attached with their source and deep-link.
3. Semantic fallback   -- chunks with no links get their nearest code file
   via BM25 over script contents, so no chunk is left without a code hook
   when a repo is provided.

Operates on ChunkRecord (chunk_id/section_header/content), not the retired
SectionRecord -- multiple chunks can share the same section_header when a
section was split across several chunks; each is linked independently.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from pathlib import Path

from rank_bm25 import BM25Okapi

from dlrag_core.config import RepoConfig, StructureConfig
from dlrag_core.models import ChunkRecord, CodeAsset

logger = logging.getLogger(__name__)

_CELL_TAG_IN_SOURCE = re.compile(r"(?i)cell[_\s-]?(\d+(?:\.\d+)*)")
_WRITEFILE = re.compile(r"%%writefile\s+([^\s]+\.py)")


@dataclass
class NotebookCell:
    cell_type: str
    source: str
    tags: set[str] = field(default_factory=set)


class RepoAssetIndex:
    """Everything the linker needs, scanned once."""

    def __init__(self, cfg: RepoConfig):
        self.cfg = cfg
        self.repo_dir = Path(cfg.local_dir).resolve() if cfg.local_dir else None
        self.notebooks: dict[str, list[NotebookCell]] = {}
        self.scripts: dict[str, str] = {}
        if self.repo_dir and self.repo_dir.is_dir():
            if cfg.include_notebooks:
                self._scan_notebooks()
            if cfg.include_scripts:
                self._scan_scripts()

    # ---------------------------------------------------------------- scan
    def _scan_notebooks(self) -> None:
        for nb_path in sorted(self.repo_dir.rglob("*.ipynb")):
            if ".ipynb_checkpoints" in nb_path.parts:
                continue
            try:
                data = json.loads(nb_path.read_text(encoding="utf-8"))
            except Exception:
                continue
            cells = []
            for cell in data.get("cells", []):
                source = "".join(cell.get("source", "")).strip()
                if not source:
                    continue
                cells.append(
                    NotebookCell(
                        cell_type=cell.get("cell_type", "code"),
                        source=source,
                        tags=set(_CELL_TAG_IN_SOURCE.findall(source)),
                    )
                )
            self.notebooks[self._rel(nb_path)] = cells

    def _scan_scripts(self) -> None:
        for ext in ("*.py", "*.js", "*.ts", "*.R", "*.java", "*.cpp", "*.c"):
            for f in sorted(self.repo_dir.rglob(ext)):
                if any(part.startswith(".") for part in f.relative_to(self.repo_dir).parts):
                    continue
                try:
                    self.scripts[self._rel(f)] = f.read_text(encoding="utf-8", errors="ignore")
                except Exception:
                    continue

    def _rel(self, path: Path) -> str:
        return path.relative_to(self.repo_dir).as_posix()

    # ---------------------------------------------------------------- urls
    def url_for(self, rel_path: str) -> str | None:
        if not self.cfg.remote_url:
            return None
        return f"{self.cfg.remote_url.rstrip('/')}/{rel_path}"


class RepoLinker:
    """Attaches GitHub links and CodeAssets to every chunk."""

    def __init__(self, cfg: RepoConfig, structure: StructureConfig):
        self.cfg = cfg
        self.structure = structure
        self.assets = RepoAssetIndex(cfg)
        self._tag_re = re.compile(structure.cell_tag_pattern)
        # Lazily-built BM25 over scripts for the semantic fallback.
        self._script_bm25: BM25Okapi | None = None
        self._script_paths: list[str] = []

    # ---------------------------------------------------------------- API
    def link(self, chunks: list[ChunkRecord]) -> list[ChunkRecord]:
        if not self.assets.repo_dir:
            return chunks
        current_nb: str | None = None
        for chunk in chunks:
            current_nb = self._match_notebook(chunk.section_header) or current_nb
            self._link_cells(chunk, current_nb)
            self._link_writefiles(chunk)
            if self.cfg.semantic_fallback and not chunk.github_links:
                self._link_semantic(chunk)
        n_linked = sum(1 for c in chunks if c.github_links)
        logger.info(
            "[Linker] Linked %d/%d chunks to repo assets (%d notebooks, %d scripts scanned).",
            n_linked,
            len(chunks),
            len(self.assets.notebooks),
            len(self.assets.scripts),
        )
        return chunks

    # ------------------------------------------------------ cascade steps
    def _match_notebook(self, section_header: str) -> str | None:
        """Fuzzy-match a section header to a notebook filename.

        Scores numeric overlap ("Chapter 3" -> ch3/chapter03/chapter3) plus
        shared alpha tokens; returns None below threshold.
        """
        title_l = section_header.lower()
        numbers = re.findall(r"\d+", title_l)
        words = set(re.findall(r"[a-z]{3,}", title_l)) - {"the", "and", "chapter", "part"}
        best, best_score = None, 0
        for nb_path in self.assets.notebooks:
            name = Path(nb_path).stem.lower().replace("_", "")
            score = sum(10 for n in numbers if n in name or n.zfill(2) in name)
            score += sum(2 for w in words if w in name)
            if score > best_score:
                best, best_score = nb_path, score
        return best if best_score >= 10 else None

    def _link_cells(self, chunk: ChunkRecord, current_nb: str | None) -> None:
        wanted = set(m.group(1) for m in self._tag_re.finditer(chunk.content))
        if not wanted:
            return
        search_space: list[str] = []
        if current_nb and current_nb in self.assets.notebooks:
            search_space.append(current_nb)
        search_space += [p for p in self.assets.notebooks if p not in search_space]

        for nb_path in search_space:
            matched = [c for c in self.assets.notebooks[nb_path] if c.tags & wanted]
            if not matched:
                continue
            self._add_link(chunk, nb_path)
            for cell in matched:
                chunk.repo_code.append(
                    CodeAsset(
                        file=f"{nb_path} (cell)",
                        url=self.assets.url_for(nb_path),
                        code=cell.source,
                        kind="notebook_cell",
                    )
                )
            wanted -= set().union(*(c.tags for c in matched))
            if not wanted:
                break

    def _link_writefiles(self, chunk: ChunkRecord) -> None:
        for rel in dict.fromkeys(_WRITEFILE.findall(chunk.content)):  # dedupe, keep order
            target = (self.assets.repo_dir / rel).resolve()
            if not str(target).startswith(str(self.assets.repo_dir)) or not target.exists():
                continue
            self._add_link(chunk, rel)
            chunk.repo_code.append(
                CodeAsset(
                    file=rel,
                    url=self.assets.url_for(rel),
                    code=target.read_text(encoding="utf-8", errors="ignore").strip(),
                    kind="writefile",
                )
            )

    def _link_semantic(self, chunk: ChunkRecord) -> None:
        if not self.assets.scripts:
            return
        if self._script_bm25 is None:
            self._script_paths = list(self.assets.scripts)
            self._script_bm25 = BM25Okapi([self._tokens(f"{p} {c}") for p, c in self.assets.scripts.items()])
        scores = self._script_bm25.get_scores(self._tokens(f"{chunk.section_header} {chunk.content[:2000]}"))
        top = int(scores.argmax()) if scores.max() > 0 else -1
        if top < 0:
            return
        rel = self._script_paths[top]
        self._add_link(chunk, rel)
        chunk.repo_code.append(
            CodeAsset(
                file=rel,
                url=self.assets.url_for(rel),
                code=self.assets.scripts[rel][: self.cfg.semantic_code_char_cap],
                kind="semantic",
            )
        )

    # ---------------------------------------------------------------- utils
    @staticmethod
    def _tokens(text: str) -> list[str]:
        return re.findall(r"[a-z0-9_]+", text.lower())

    def _add_link(self, chunk: ChunkRecord, rel_path: str) -> None:
        url = self.assets.url_for(rel_path) or f"local:{rel_path}"
        if url not in chunk.github_links:
            chunk.github_links.append(url)
